# '+' and '*' operators using lists and tuples
# 1.list
list1 = [1, 2, 3]
list2 = [4, 5, 6]
concatenated_list = list1 + list2
print("Concatenated list:", concatenated_list)
multiplied_list = list1 * 3 # This will repeat the list 3 times not multiplied by 3 in sequence
print("Multiplied list:", multiplied_list)

# 2.tuple
tuple1 = (1, 2, 3)
tuple2 = (4, 5, 6)
concatenated_tuple = tuple1 + tuple2
print("Concatenated tuple:", concatenated_tuple)
multiplied_tuple = tuple1 * 3 # This will repeat the tuple 3 times not multiplied by 3 in sequence
print("Multiplied tuple:", multiplied_tuple)